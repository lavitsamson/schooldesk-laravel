#!/usr/bin/env bash
# Production-like benchmark run (README: "Performance"), inside the Sail container:
#
#   ./vendor/bin/sail artisan db:seed --class=PerformanceSeeder
#   ./vendor/bin/sail bash scripts/benchmark.sh [--runs=30] [--school=perf-01] [--no-batch]
#
# Copies the app (without node_modules) to the container's own file system first: on a
# Windows or macOS bind mount every request pays ~85 ms just for reading the framework's
# files, which no server has. The copy gets what a deployment gets (optimised autoloader,
# cached config, routes, views and events, opcache, APP_DEBUG=false) and is served on :8001
# by PHP's built-in server with two workers. The dev checkout is left untouched.
# Report cards are generated by Horizon, which must be running (it uses the mounted code).
set -euo pipefail

src=/var/www/html
copy=/tmp/schooldesk-benchmark

rm -rf "$copy"
mkdir -p "$copy"
tar -C "$src" --exclude=./node_modules --exclude=./.git --exclude=./storage/logs --exclude=./storage/app \
    --exclude=./storage/framework/cache --exclude=./storage/framework/views --exclude=./test-results -cf - . | tar -C "$copy" -xf -
mkdir -p "$copy/storage/logs" "$copy/storage/app/private" "$copy/storage/framework/cache" "$copy/storage/framework/views"

cd "$copy"
composer dump-autoload --optimize --quiet
APP_DEBUG=false php artisan optimize > /dev/null

cd "$copy/public"
APP_DEBUG=false PHP_CLI_SERVER_WORKERS=2 php -d opcache.enable_cli=1 -d opcache.validate_timestamps=0 \
    -d opcache.memory_consumption=256 -d opcache.max_accelerated_files=20000 \
    -S 0.0.0.0:8001 ../vendor/laravel/framework/src/Illuminate/Foundation/resources/server.php > "$copy/storage/logs/server.log" 2>&1 &
server=$!
trap 'kill $server 2> /dev/null || true' EXIT
sleep 2

node "$src/scripts/benchmark.mjs" --base=http://127.0.0.1:8001 "$@"
