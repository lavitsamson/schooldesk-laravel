/**
 * The school's audit log entries, newest last.
 *
 * @return Collection<int, Activity>
 */
function auditLog(School $school): Collection
{
    return inSchool($school, fn () => Activity::query()->orderBy('id')->get());
}

it('logs student changes for the student\'s school, with who made them', function (): void {
    [$school] = setUpSchool();
    $admin = memberOf($school);
    $student = Student::factory()->for($school)->create(['first_name' => 'Ada', 'address' => 'Old Road 1']);

    $this->actingAs($admin);
    inSchool($school, fn () => $student->update(['address' => 'New Road 2', 'photo_path' => 'photos/ada.jpg']));

    [$created, $updated] = auditLog($school)->all();

    // Created by the factory: no user, but still the student's school.
    expect($created->school_id)->toBe($school->id)
        ->and($created->log_name)->toBe(ActivityArea::Students->value)
        ->and($created->event)->toBe('created')
        ->and($created->causer_id)->toBeNull()
        ->and($created->student_id)->toBe($student->id)
        ->and($created->attribute_changes?->get('attributes'))->toMatchArray(['first_name' => 'Ada', 'status' => 'active'])
        ->and($created->attribute_changes?->get('attributes'))->not->toHaveKey('photo_path');

    // Only the logged attribute that changed; the photo path is not logged.
    expect($updated->event)->toBe('updated')
        ->and($updated->causer_id)->toBe($admin->id)
        ->and($updated->subject_type)->toBe('student')
        ->and($updated->attribute_changes?->all())->toEqual([
            'attributes' => ['address' => 'New Road 2'],
            'old' => ['address' => 'Old Road 1'],
        ]);
});

it('leaves no entry when only unlogged attributes change', function (): void {
    [$school] = setUpSchool();
    $student = Student::factory()->for($school)->create();

    inSchool($school, fn () => $student->update(['photo_path' => 'photos/x.jpg']));

    expect(auditLog($school))->toHaveCount(1);
});

it('logs marks with the student they belong to', function (): void {
    $setup = setUpReportCards();
    $grade = inSchool($setup['school'], fn () => Grade::query()->where('student_id', $setup['students'][0]->id)->sole());

    $this->actingAs($setup['teacher']);
    inSchool($setup['school'], function () use ($grade): void {
        $grade->update(['marks' => '19']);
        $grade->delete();
    });

    $entries = auditLog($setup['school'])->where('log_name', ActivityArea::Grades->value)->values();

    expect($entries->pluck('event')->all())->toBe(['created', 'created', 'updated', 'deleted'])
        ->and($entries[2]->student_id)->toBe($setup['students'][0]->id)
        ->and($entries[2]->causer_id)->toBe($setup['teacher']->id)
        ->and($entries[2]->attribute_changes?->all())->toEqual(['attributes' => ['marks' => '19.00'], 'old' => ['marks' => '18.00']])
        ->and($entries[3]->attribute_changes?->get('old'))->toMatchArray(['marks' => '19.00']);
});

it('logs generated invoices, payments and voiding, but not reminders', function (): void {
    Queue::fake();
    Storage::fake('local');
    $this->travelTo('2026-08-05 10:00:00');
    $setup = setUpFees();
    generateInvoices($setup['school'], $setup['term']);
    $invoice = inSchool($setup['school'], fn () => Invoice::query()->where('student_id', $setup['students'][0]->id)->sole());
    $other = inSchool($setup['school'], fn () => Invoice::query()->where('student_id', $setup['students'][1]->id)->sole());

    $this->actingAs($setup['admin']);
    inSchool($setup['school'], function () use ($invoice, $other, $setup): void {
        $invoice->increment('reminders_sent');
        app(RecordPayment::class)->handle($invoice, new Money(50_000, 'EUR'), PaymentMethod::Cash, $setup['admin'], now());
        $other->update(['status' => InvoiceStatus::Void, 'voided_at' => now()]);
    });

    $entries = auditLog($setup['school']);
    $invoices = $entries->where('log_name', ActivityArea::Invoices->value)->values();
    $payment = $entries->where('log_name', ActivityArea::Payments->value)->sole();

    // Three generated by the daily run (no user), then the payment's status change and the void.
    expect($invoices->pluck('event')->all())->toBe(['created', 'created', 'created', 'updated', 'updated'])
        ->and($invoices[0]->causer_id)->toBeNull()
        ->and($invoices[0]->attribute_changes?->get('attributes'))->toMatchArray(['number' => 'SD-2026-000001', 'total' => 120_000, 'status' => 'issued'])
        ->and($invoices[3]->attribute_changes?->all())->toEqual(['attributes' => ['status' => 'partially_paid'], 'old' => ['status' => 'issued']])
        ->and($invoices[4]->student_id)->toBe($setup['students'][1]->id)
        ->and($payment->student_id)->toBe($setup['students'][0]->id)
        ->and($payment->causer_id)->toBe($setup['admin']->id)
        ->and($payment->attribute_changes?->get('attributes'))->toMatchArray(['amount' => 50_000, 'method' => 'cash']);
});

it('logs report card approvals, publishing and reopening, but not generation', function (): void {
    $setup = setUpReportCards();
    $card = reportCardFor($setup['school'], $setup['students'][0], $setup['term'], $setup['class']);
    reportCardFor($setup['school'], $setup['students'][0], $setup['term'], $setup['class']);

    $this->actingAs($setup['classTeacher']);
    inSchool($setup['school'], function () use ($card): void {
        $card->update(['teacher_comment' => 'Well done.']);
        $card->update(['status' => ReportCardStatus::Approved]);
        $card->update(['status' => ReportCardStatus::Draft]);
        $card->update(['status' => ReportCardStatus::Approved]);
        $card->update(['status' => ReportCardStatus::Published]);
    });

    $entries = auditLog($setup['school'])->where('log_name', ActivityArea::ReportCards->value)->values();

    expect($entries->pluck('description')->all())->toBe(['approved', 'reopened', 'approved', 'published'])
        ->and($entries[0]->causer_id)->toBe($setup['classTeacher']->id)
        ->and($entries[0]->student_id)->toBe($setup['students'][0]->id)
        ->and($entries[0]->attribute_changes?->all())->toEqual(['attributes' => ['status' => 'approved'], 'old' => ['status' => 'draft']]);
});

